import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const json=p=>JSON.parse(read(p));
const ctx=vm.createContext({});
vm.runInContext(read('js/br-data-pulse.js'),ctx);
const p=ctx.FDGDataPulse;
const R=json('resultados.json'),T=json('tabela.json');
const ref=p.reconcile(R.resultados,T.tabela);
assert.equal(ref.certified,true,'official ledger and table must reconcile');
assert.equal(ref.expected,R.resultados.length);
assert.equal(p.reconcile([...R.resultados,R.resultados[0]],T.tabela).certified,false);
assert.equal(p.reconcile(R.resultados.map((g,i)=>i?g:{...g,placar_mandante:g.placar_mandante+1}),T.tabela).certified,false);
assert.equal(p.compareGames(ref,R.resultados).certified,true);
assert.equal(p.compareGames(ref,R.resultados.slice(1)).certified,false);
assert.equal(p.compareGames(ref,R.resultados.map((g,i)=>i?g:{...g,placar_visitante:g.placar_visitante+1})).certified,false);
assert.equal(p.model({processed:356,expected:359,certified:true,updatedAt:R.atualizado_em}).status,'pending');
assert.equal(p.model({processed:359,expected:359,certified:false,updatedAt:R.atualizado_em}).status,'unknown');
assert.equal(p.model({processed:359,expected:359,certified:true,updatedAt:'invalid'}).status,'unknown');
assert.equal(p.model({processed:359,expected:359,certified:true,updatedAt:R.atualizado_em,pending:true}).status,'pending');
const E3=json('dados-br/resultados-af-placares-2026.json'),E4=json('dados-br/acuracia-placares-af-2026.json');
const proof=p.accuracyProof(ref,E3,E4);
assert.equal(proof.audited,ref.expected,'E3 must cover current official finals');
assert.equal(proof.certified,true,'E3/E4 must reconcile against official ledger');
assert.equal(proof.expected,E3.resumo.previsoes_certificadas);
assert.equal(proof.processed,proof.expected);
assert.equal(p.accuracyProof(ref,E3,{...E4,jogos:[...E4.jogos,E4.jogos[0]]}).certified,false);
assert.equal(p.accuracyProof(ref,E3,{...E4,jogos:E4.jogos.slice(1)}).certified,false);
assert.equal(p.accuracyProof(ref,E3,{...E4,jogos:E4.jogos.map((g,i)=>i?g:{...g,commit_prova:'0'.repeat(40)})}).certified,false);
assert.equal(p.accuracyProof(ref,E3,{...E4,jogos:E4.jogos.map((g,i)=>i?g:{...g,placar_final:{...g.placar_final,mandante:g.placar_final.mandante+1}})}).certified,false);
for(const path of ['js/br-estatisticas.js','js/br-acuracia.js','js/br-acuracia-placares-e4.js'])new vm.Script(read(path));
console.log('PASS Data Pulse D: ledger, revisions, duplicates, eligibility, evidence and syntax',JSON.stringify(proof));
