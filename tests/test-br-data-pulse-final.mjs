import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFileSync} from 'node:fs';
const read=p=>readFileSync(p,'utf8');
const ctx=vm.createContext({});
vm.runInContext(read('js/br-data-refresh.js'),ctx);
const api=ctx.FDGRefreshScheduler;
let now=0,visible=true,active=false,timers=new Map(),seq=0,runs=0,release;
const scheduler=api.create({run:()=>{runs++;return new Promise(r=>release=r)},active:()=>active,visible:()=>visible,clock:()=>now,setTimer:(fn,delay)=>{timers.set(++seq,{fn,at:now+delay});return seq},clearTimer:id=>timers.delete(id)});
const fire=async()=>{const [id,t]=[...timers][0];timers.delete(id);now=t.at;const task=t.fn();await Promise.resolve();return {task}};
const finish=async task=>{release();await task};
scheduler.start();assert.equal([...timers.values()][0].at,60000);
scheduler.wake();assert.equal([...timers.values()][0].at,0);
let {task}=await fire();assert.equal(runs,1);
scheduler.wake();scheduler.wake();assert.equal(timers.size,0);assert.equal(scheduler.status().queued,true);
await finish(task);assert.equal(timers.size,1);assert.equal([...timers.values()][0].at,2000);
active=true;({task}=await fire());await finish(task);assert.equal([...timers.values()][0].at,14000);
visible=false;scheduler.pause();assert.equal(timers.size,0);scheduler.wake();assert.equal(timers.size,0);
visible=true;scheduler.wake();({task}=await fire());await finish(task);assert.equal(runs,3);
scheduler.stop();assert.equal(timers.size,0);
const rows=[{eventId:'1',estado:'post',placarMandante:2,placarVisitante:1},{eventId:'2',estado:'in'}];
assert.equal(api.finalKey(rows),'1:2:1');assert.equal(api.finalKey(rows,[],(g,ref=new Date())=>ref instanceof Date&&g.estado==='post'),'1:2:1');assert.equal(api.finalKey([...rows,rows[0]]),'1:2:1');
assert.equal(api.finalKey(rows,[{event_id:'1'}]),'');assert.equal(api.finalKey([{...rows[0],placarMandante:3}]),'1:3:1');
for(const file of ['js/br-estatisticas.js','js/br-af-core-snapshot.js','js/br-data-refresh.js'])new vm.Script(read(file));
const index=read('index.html'),stats=read('js/br-estatisticas.js'),html=read('estatisticas.html');
assert.ok(index.includes('fdgCoreScheduler.wake()'));assert.ok(stats.includes('refreshState.scheduler?.wake()'));
assert.ok(index.includes('br-data-refresh.js?v=20261124-r36r5final'));assert.ok(html.includes('br-data-refresh.js?v=20261124-r36r5final'));
assert.ok(read('js/br-af-core-snapshot.js').includes('urgent?12000:45000'));
console.log('PASS FDG FINAL: adaptive schedule, single flight, trailing wake, visibility, FINAL dedup, syntax and integration');
