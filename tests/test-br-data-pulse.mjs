import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const context=vm.createContext({});
const js=readFileSync(new URL('../js/br-data-pulse.js',import.meta.url),'utf8');
vm.runInContext(js,context);
const p=context.FDGDataPulse;
const base={updatedAt:'2026-11-23T22:20:03-03:00',processed:358,expected:358,certified:true,seasonTotal:380,seasonCompleted:358};
assert.equal(p.model(base).status,'synced');
assert.equal(p.model(base).remaining,22);
assert.equal(p.model(base).stamp.time,'22:20:03');
assert.equal(p.model({...base,certified:false}).status,'unknown');
assert.equal(p.model({...base,processed:356}).status,'pending');
assert.equal(p.model({...base,live:true}).status,'live');
assert.equal(p.model({...base,late:true}).status,'late');
assert.equal(p.model({...base,pending:true,live:true}).status,'pending');
assert.equal(p.model({...base,updatedAt:'invalid'}).status,'unknown');
assert.equal(p.model({...base,updatedAt:'2026-11-23T22:20:03'}).status,'unknown');
assert.equal(p.model({...base,processed:359}).coverage,null);
assert.equal(p.model({...base,expected:0,processed:0}).status,'unknown');
assert.equal(p.model({...base,processed:null}).coverage,null);
const html=p.render({...base,metrics:[{label:'Simulações',value:'2.000.000'}]});
assert.match(html,/358\/358/);
assert.match(html,/358\/380/);
assert.match(html,/22:20:03/);
assert.match(html,/2\.000\.000/);
assert.match(html,/aria-valuenow="100.00"/);
assert.match(html,/ATUALIZADO/);
assert.doesNotMatch(p.render({...base,note:'<script>alert(1)</script>'}),/<script>/);
assert.doesNotMatch(p.render({...base,certified:false}),/fdg-pulse-positive/);
const el={innerHTML:''};
assert.equal(p.mount(el,base),true);
assert.match(el.innerHTML,/FDG DATA PULSE/);
assert.equal(p.mount(null,base),false);
assert.doesNotMatch(js,/\b(fetch|setInterval|setTimeout)\s*\(/);
const css=readFileSync(new URL('../css/br-data-pulse.css',import.meta.url),'utf8');
assert.match(css,/repeat\(2,minmax\(0,1fr\)\)/);
assert.match(css,/prefers-reduced-motion/);
console.log('PASS R36-R5 A: states, timestamp, coverage, escaping, responsive CSS and zero network');
