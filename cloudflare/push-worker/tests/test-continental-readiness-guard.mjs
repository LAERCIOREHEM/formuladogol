import assert from 'node:assert/strict';
import { readinessSnapshot, continentalReadinessPreOnly, CONTINENTAL_READINESS_GRACE_MS } from '../src/readiness-guardian.js';
const kickoff = '2026-10-14T21:30:00-03:00';
const now = Date.parse(kickoff) + 3 * 60_000;
const game = { eventId:'fdg-conmebol-libertadores-202610142130-fluminense-palmeiras', sourceEventId:'401912522', league:'conmebol.libertadores', kickoff, home:{id:'1',name:'Fluminense'},away:{id:'2',name:'Palmeiras'} };
const raw = {id:'401912522',date:kickoff,status:{type:{state:'pre'}},competitions:[{competitors:[{homeAway:'home',team:{id:'1',displayName:'Fluminense'}},{homeAway:'away',team:{id:'2',displayName:'Palmeiras'}}]}]};
const resolved={raw,sourceEventId:'401912522',strategy:'event_id'};
const pre=readinessSnapshot(game,resolved,{initialized:true,state:'pre'}, {},'tplus3',now);
assert.equal(pre.ready,false);
assert.deepEqual(pre.reasons,['espn_still_pre_after_tplus3']);
assert.equal(continentalReadinessPreOnly(game,pre),true);
assert.equal(CONTINENTAL_READINESS_GRACE_MS,600000);
const started=readinessSnapshot(game,resolved,{initialized:true,state:'in'}, {},'tplus3',now);
assert.equal(started.ready,true);
assert.ok(started.warnings.includes('espn_pre_but_monitor_started'));
assert.equal(continentalReadinessPreOnly(game,started),false);
const absent=readinessSnapshot(game,null,{initialized:true,state:'pre'}, {},'tplus3',now);
assert.equal(continentalReadinessPreOnly(game,absent),false);
const notInitialized=readinessSnapshot(game,resolved,{initialized:false,state:'pre'}, {},'tplus3',now);
assert.equal(continentalReadinessPreOnly(game,notInitialized),false);
const br=readinessSnapshot({...game,league:'bra.1'},resolved,{initialized:true,state:'pre'}, {},'tplus3',now);
assert.equal(continentalReadinessPreOnly({...game,league:'bra.1'},br),true, 'R10R17.8: Série A também tem tolerância ESPN PRE');
assert.equal(continentalReadinessPreOnly({...game,league:'bra.2'},br),false, 'outras ligas não ganham tolerância indevida');
console.log('PASS R10R17.4/R10R17.8: continental + Serie A ESPN PRE false-alarm guard');
